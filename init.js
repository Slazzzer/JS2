// Инициализация при загрузке страницы
document.addEventListener('DOMContentLoaded', () => {
    // === ФИЛЬТРАЦИЯ И ПОИСК ===
    
    // Инициализация выпадающего списка фильтрации (dropdown в шапке)
    // Отвечает за открытие/закрытие меню и выбор категории
    const dropdown = document.getElementById('customDropdown');
    if (dropdown) {
        initCustomDropdown(dropdown);
    }

    // Инициализация фильтрации по категориям (кнопки в сайдбаре: "Все новости", "Спорт", "Общество", "Экономика")
    // Обрабатывает клики по кнопкам категорий в левой панели
    initNewsFilter();

    // Инициализация поиска по категориям (поле "Поиск" в сайдбаре)
    // Обрабатывает ввод текста в поле поиска и фильтрует карточки
    initSearch();

    // === АНИМАЦИИ ===
    
    // Анимация появления карточек при загрузке страницы
    // Использует Intersection Observer для плавного появления карточек при прокрутке
    animateCards();

    // Анимация 3D вращения карточек при наведении (эффект "юлы")
    // Карточки вращаются вокруг своей оси против часовой стрелки при наведении
    setupCardAnimations();

    // Анимации элементов сайдбара при наведении
    // Добавляет плавные переходы для элементов навигации
    setupSidebarAnimations();

    // Анимация вращения и движения логотипа по периметру экрана
    // При клике на логотип он вращается и движется по прямоугольнику экрана
    setupLogoRotation();

    // Анимация самолета при клике на футер сайдбара
    // Самолет летит через весь экран, футер блокируется на время анимации
    setupAirplaneAnimation();

    // Эффект "убегания" текста "Вариант 4" от курсора мыши
    // Текст отодвигается от курсора при приближении к нему
    setupRunawayText();

    // Вращение заголовка "Все контакты" при наведении мыши
    // Заголовок вращается по окружности, следуя за курсором
    // При клике меняется направление вращения (по/против часовой стрелки)
    setupHeaderRotation();

    // Анимация появления заголовка "Все контакты" при загрузке
    const title = document.querySelector('.main-header h1');
    if (title) {
        title.style.animation = 'fadeIn 0.6s ease-out';
    }

    // Анимации при прокрутке страницы
    // Показывает карточки, которые попадают в область видимости при скролле
    setupScrollAnimations();
});
